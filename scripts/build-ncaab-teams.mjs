// Generates src/lib/ncaab-teams.generated.ts from ESPN's men's college
// basketball teams API (Division I, groups=50). Run: node scripts/build-ncaab-teams.mjs
// The output is committed; re-run when ESPN adds or renames a program.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const TEAMS_URL =
  "https://site.api.espn.com/apis/site/v2/sports/basketball/mens-college-basketball/teams?limit=1000&groups=50";
const OUT = fileURLToPath(new URL("../src/lib/ncaab-teams.generated.ts", import.meta.url));

const res = await fetch(TEAMS_URL);
if (!res.ok) throw new Error(`ESPN teams fetch failed: ${res.status}`);
const body = await res.json();
const raw = body?.sports?.[0]?.leagues?.[0]?.teams ?? [];
if (raw.length < 300) throw new Error(`Expected 300+ D1 teams, got ${raw.length}`);

const rows = new Map();
for (const { team } of raw) {
  const abbr = String(team?.abbreviation ?? "").trim().toUpperCase();
  const id = String(team?.id ?? "").trim();
  if (!abbr || !/^\d+$/.test(id)) continue;
  if (rows.has(abbr)) {
    console.warn(`duplicate abbreviation ${abbr}: keeping id ${rows.get(abbr).id}, skipping ${id}`);
    continue;
  }
  const name = String(team.location ?? team.shortDisplayName ?? team.displayName ?? abbr).trim();
  const color = /^[0-9a-fA-F]{6}$/.test(team.color ?? "") ? `#${team.color.toLowerCase()}` : null;
  rows.set(abbr, { id, name, color });
}

const sorted = [...rows.entries()].sort(([a], [b]) => a.localeCompare(b));
const lines = sorted.map(
  ([abbr, t]) => `  ${JSON.stringify(abbr)}: { id: ${JSON.stringify(t.id)}, name: ${JSON.stringify(t.name)}, color: ${JSON.stringify(t.color)} },`,
);
const src = `// GENERATED by scripts/build-ncaab-teams.mjs from ESPN. Do not edit by hand.
// ${sorted.length} Division I programs: ESPN abbreviation -> team id, short name, color.

export interface NcaabTeamRow {
  id: string;
  name: string;
  color: string | null;
}

export const NCAAB_TEAMS: Record<string, NcaabTeamRow> = {
${lines.join("\n")}
};
`;
writeFileSync(OUT, src);
console.log(`wrote ${sorted.length} teams to ${OUT}`);
